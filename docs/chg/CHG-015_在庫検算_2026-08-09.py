UNIT=250
def run(rows,adj,lots,name):
    print("==",name); ok=True
    for d,recv,ng,dlv,box,rep in rows:
        # 1) 検品（名目数＝箱数×入数のロットを預かりに追加。NG・箱の過不足は調整用で埋める）
        if recv is not None:
            nominal=round(recv/UNIT)*UNIT; diff=recv-nominal
            adj+= -ng + diff
            lots.append([d,nominal])
        # 2) 調整用に1箱回す（当日のロットから）
        if box:
            lots[-1][1]-=box*UNIT; adj+=box*UNIT
        # 3) 納入（古いロットから。先入れ先出し。当日分を同日に納入することもある）
        need=dlv
        while need>0:
            q=lots[0][1]; take=min(q,need); lots[0][1]-=take; need-=take
            if lots[0][1]==0: lots.pop(0)
        dep=sum(q for _,q in lots)
        flag="" if adj==rep else "  <-- 不一致"
        ok&=adj==rep
        print(f"{d} 調整用 {adj:>4}（記載 {rep:>4}）預かり {dep:>5} 未納入ロット {lots}{flag}")
    return adj,lots,ok
